-- =====================================================================
-- Pokeplan :: Layer 3 — MART (a.k.a. gold / presentation)
-- ---------------------------------------------------------------------
-- Kimball star schema. Rules applied throughout:
--   * Every table states its GRAIN (what one row means) before anything
--     else. Facts never mix grains.
--   * Dimensions get an integer SURROGATE key (<name>_key) plus the API's
--     NATURAL key (<name>_id, unique). Facts join on surrogate keys only.
--   * Hierarchies are flattened into the dimension (denormalised), e.g.
--     version -> version group -> generation lives in dim_version. That is
--     what makes it a star and not a snowflake.
--   * Surrogate keys are identity columns starting at 1. Key 0 is the
--     "Unknown / Not applicable" member in every dimension,
--     so facts never hold NULL foreign keys and inner joins never drop rows.
--   * Every row carries audit columns (_batch_id, _loaded_at, _row_hash).
--   * Dimensions are SCD type 1 (overwrite) unless stated otherwise;
--     row_hash lets the loader skip unchanged rows.
-- =====================================================================

CREATE SCHEMA IF NOT EXISTS mart;

-- ============================ DIMENSIONS =============================

-- Grain: one row per generation (I .. IX). ~9 rows.
CREATE TABLE IF NOT EXISTS mart.dim_generation (
    generation_key      smallint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    generation_id       smallint NOT NULL UNIQUE,
    generation_code     text     NOT NULL,          -- 'generation-i'
    generation_name     text,                       -- 'Generation I'
    generation_number   smallint NOT NULL,          -- 1 (sortable)
    main_region_code    text,
    _batch_id bigint, _loaded_at timestamptz DEFAULT now(), _row_hash text
);

-- Grain: one row per version group. Role-played in facts as "the games
-- this fact applies to". ~27 rows.
CREATE TABLE IF NOT EXISTS mart.dim_version_group (
    version_group_key   smallint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version_group_id    smallint NOT NULL UNIQUE,
    version_group_code  text     NOT NULL,          -- 'red-blue'
    sort_order          smallint,
    generation_id       smallint,                   -- denormalised hierarchy
    generation_code     text,
    generation_number   smallint,
    _batch_id bigint, _loaded_at timestamptz DEFAULT now(), _row_hash text
);

-- Grain: one row per individual game version. ~45 rows.
CREATE TABLE IF NOT EXISTS mart.dim_version (
    version_key         smallint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version_id          smallint NOT NULL UNIQUE,
    version_code        text     NOT NULL,          -- 'red'
    version_name        text,
    version_group_id    smallint,                   -- denormalised hierarchy
    version_group_code  text,
    generation_id       smallint,
    generation_code     text,
    generation_number   smallint,
    _batch_id bigint, _loaded_at timestamptz DEFAULT now(), _row_hash text
);

-- Grain: one row per elemental type. Role-played as attacking/defending
-- type in fact_type_effectiveness and as move type in dim_move. ~21 rows.
CREATE TABLE IF NOT EXISTS mart.dim_type (
    type_key            smallint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    type_id             integer  NOT NULL UNIQUE,
    type_code           text     NOT NULL,          -- 'fire'
    type_name           text,
    introduced_generation smallint,
    is_battle_type      boolean  NOT NULL DEFAULT true, -- false for unknown/shadow/stellar
    _batch_id bigint, _loaded_at timestamptz DEFAULT now(), _row_hash text
);

-- Grain: one row per stat (hp, attack, ..., accuracy, evasion). 8 rows.
CREATE TABLE IF NOT EXISTS mart.dim_stat (
    stat_key            smallint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    stat_id             smallint NOT NULL UNIQUE,
    stat_code           text     NOT NULL,
    stat_name           text,
    is_battle_only      boolean,
    display_order       smallint,
    _batch_id bigint, _loaded_at timestamptz DEFAULT now(), _row_hash text
);

-- Grain: one row per ability. ~370 rows.
CREATE TABLE IF NOT EXISTS mart.dim_ability (
    ability_key         integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ability_id          integer  NOT NULL UNIQUE,
    ability_code        text     NOT NULL,
    ability_name        text,
    short_effect        text,
    is_main_series      boolean,
    introduced_generation smallint,
    _batch_id bigint, _loaded_at timestamptz DEFAULT now(), _row_hash text
);

-- Grain: one row per move, CURRENT values (SCD1). Historic power/accuracy
-- per version group is available in move.past_values: a natural next
-- step is to make this SCD type 2 keyed on version group. ~940 rows.
CREATE TABLE IF NOT EXISTS mart.dim_move (
    move_key            integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    move_id             integer  NOT NULL UNIQUE,
    move_code           text     NOT NULL,
    move_name           text,
    type_code           text,                       -- denormalised from type
    damage_class        text,                       -- physical / special / status
    power               smallint,                   -- NULL for status moves
    accuracy            smallint,
    pp                  smallint,
    priority            smallint,
    effect_chance       smallint,
    target              text,
    ailment             text,
    move_category       text,
    introduced_generation smallint,
    _batch_id bigint, _loaded_at timestamptz DEFAULT now(), _row_hash text
);

-- Grain: one row per item. ~2,200 rows.
CREATE TABLE IF NOT EXISTS mart.dim_item (
    item_key            integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    item_id             integer  NOT NULL UNIQUE,
    item_code           text     NOT NULL,
    item_name           text,
    category            text,
    cost                integer,
    fling_power         smallint,
    fling_effect        text,
    is_holdable         boolean,
    _batch_id bigint, _loaded_at timestamptz DEFAULT now(), _row_hash text
);

-- Grain: one row per location area; location and region flattened in.
-- ~1,100 rows.
CREATE TABLE IF NOT EXISTS mart.dim_location_area (
    location_area_key   integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    location_area_id    integer  NOT NULL UNIQUE,
    location_area_code  text     NOT NULL,
    location_area_name  text,
    location_id         integer,
    location_code       text,
    location_name       text,
    region_code         text,
    _batch_id bigint, _loaded_at timestamptz DEFAULT now(), _row_hash text
);

-- Grain: one row per species (the "Pokedex entry": Raticate). ~1,025 rows.
-- Used by fact_evolution, where evolution happens between species.
CREATE TABLE IF NOT EXISTS mart.dim_species (
    species_key         integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    species_id          integer  NOT NULL UNIQUE,
    species_code        text     NOT NULL,
    species_name        text,
    genus               text,
    generation_number   smallint,
    evolution_chain_id  integer,
    is_baby             boolean,
    is_legendary        boolean,
    is_mythical         boolean,
    capture_rate        smallint,
    base_happiness      smallint,
    gender_rate         smallint,                   -- eighths female, -1 = genderless
    hatch_counter       smallint,
    growth_rate         text,
    color               text,
    shape               text,
    habitat             text,
    _batch_id bigint, _loaded_at timestamptz DEFAULT now(), _row_hash text
);

-- Grain: one row per pokemon (a battle-ready variety: raticate and
-- raticate-alola are two rows of one species). ~1,300 rows.
-- Species attributes are copied in (denormalised) so most queries need
-- only this one dimension. The two current types are also copied in as
-- a convenience; fact_pokemon_type holds the full, generation-dated truth.
CREATE TABLE IF NOT EXISTS mart.dim_pokemon (
    pokemon_key         integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pokemon_id          integer  NOT NULL UNIQUE,
    pokemon_code        text     NOT NULL,          -- 'raticate-alola'
    is_default_form     boolean,
    height_m            numeric(5,1),               -- API gives decimetres
    weight_kg           numeric(6,1),               -- API gives hectograms
    base_experience     smallint,
    primary_type        text,
    secondary_type      text,
    -- denormalised from species
    species_id          integer,
    species_code        text,
    species_name        text,
    generation_number   smallint,
    is_legendary        boolean,
    is_mythical         boolean,
    is_baby             boolean,
    capture_rate        smallint,
    growth_rate         text,
    color               text,
    habitat             text,
    _batch_id bigint, _loaded_at timestamptz DEFAULT now(), _row_hash text
);

-- Grain: one row per move learn method (level-up, machine, egg, tutor...).
CREATE TABLE IF NOT EXISTS mart.dim_learn_method (
    learn_method_key    smallint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    learn_method_id     smallint NOT NULL UNIQUE,
    learn_method_code   text     NOT NULL,
    learn_method_name   text,
    _batch_id bigint, _loaded_at timestamptz DEFAULT now(), _row_hash text
);

-- Grain: one row per encounter method (walk, surf, old-rod...).
CREATE TABLE IF NOT EXISTS mart.dim_encounter_method (
    encounter_method_key  smallint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    encounter_method_id   smallint NOT NULL UNIQUE,
    encounter_method_code text     NOT NULL,
    encounter_method_name text,
    _batch_id bigint, _loaded_at timestamptz DEFAULT now(), _row_hash text
);

-- JUNK DIMENSION. Grain: one row per distinct *combination* of encounter
-- condition values (e.g. 'time-night,season-winter'). An encounter can
-- have 0..n conditions; instead of a bridge table we store each observed
-- combination once and give the fact a single key. Key 0 = no condition.
CREATE TABLE IF NOT EXISTS mart.dim_encounter_condition_set (
    condition_set_key   integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    condition_set_code  text     NOT NULL UNIQUE,   -- sorted, comma-joined; '' = none
    condition_count     smallint NOT NULL,
    has_time_condition    boolean NOT NULL,
    has_season_condition  boolean NOT NULL,
    has_swarm_condition   boolean NOT NULL,
    has_radar_condition   boolean NOT NULL,
    _batch_id bigint, _loaded_at timestamptz DEFAULT now()
);

-- Grain: one row per evolution trigger (level-up, trade, use-item, ...).
CREATE TABLE IF NOT EXISTS mart.dim_evolution_trigger (
    evolution_trigger_key  smallint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    evolution_trigger_id   smallint NOT NULL UNIQUE,
    evolution_trigger_code text     NOT NULL,
    evolution_trigger_name text,
    _batch_id bigint, _loaded_at timestamptz DEFAULT now(), _row_hash text
);

-- ============================== FACTS ================================
-- Fact types used:
--   transaction-style  : fact_pokemon_move, fact_encounter, fact_evolution
--   attribute snapshot : fact_pokemon_stat, fact_pokemon_held_item
--   factless           : fact_pokemon_type, fact_pokemon_ability
--   dense matrix       : fact_type_effectiveness
-- Measures are tagged additive (A), semi-additive (S), non-additive (N).

-- Grain: one row per pokemon x move x version_group x learn_method.
-- The largest table (~600k rows). Answers "which moves can X learn in
-- game Y, how, and at what level". COUNT(*) = movepool size.
CREATE TABLE IF NOT EXISTS mart.fact_pokemon_move (
    pokemon_key         integer  NOT NULL REFERENCES mart.dim_pokemon,
    move_key            integer  NOT NULL REFERENCES mart.dim_move,
    version_group_key   smallint NOT NULL REFERENCES mart.dim_version_group,
    learn_method_key    smallint NOT NULL REFERENCES mart.dim_learn_method,
    level_learned_at    smallint NOT NULL,          -- (N) 0 when not level-up
    learn_order         smallint,                   -- (N) tie-break within a level
    _batch_id bigint, _loaded_at timestamptz DEFAULT now(),
    PRIMARY KEY (pokemon_key, move_key, version_group_key, learn_method_key)
);
CREATE INDEX IF NOT EXISTS ix_fpm_move ON mart.fact_pokemon_move (move_key);
CREATE INDEX IF NOT EXISTS ix_fpm_vg   ON mart.fact_pokemon_move (version_group_key);

-- Grain: one row per pokemon x stat (current base stats). ~7,800 rows.
-- SUM(base_stat) over the six stats = Base Stat Total.
CREATE TABLE IF NOT EXISTS mart.fact_pokemon_stat (
    pokemon_key         integer  NOT NULL REFERENCES mart.dim_pokemon,
    stat_key            smallint NOT NULL REFERENCES mart.dim_stat,
    base_stat           smallint NOT NULL,          -- (A across stats, N across pokemon)
    effort_yield        smallint NOT NULL,          -- (A) EVs awarded when defeated
    _batch_id bigint, _loaded_at timestamptz DEFAULT now(),
    PRIMARY KEY (pokemon_key, stat_key)
);

-- Grain: one encounter slot = location_area x pokemon x version x slot_seq.
-- slot_seq is a DEGENERATE DIMENSION (the position in the source array):
-- the API can list two identical slots, and both are real.
CREATE TABLE IF NOT EXISTS mart.fact_encounter (
    location_area_key     integer  NOT NULL REFERENCES mart.dim_location_area,
    pokemon_key           integer  NOT NULL REFERENCES mart.dim_pokemon,
    version_key           smallint NOT NULL REFERENCES mart.dim_version,
    slot_seq              smallint NOT NULL,        -- degenerate dimension
    encounter_method_key  smallint NOT NULL REFERENCES mart.dim_encounter_method,
    condition_set_key     integer  NOT NULL REFERENCES mart.dim_encounter_condition_set,
    min_level             smallint NOT NULL,        -- (N)
    max_level             smallint NOT NULL,        -- (N)
    chance_pct            smallint NOT NULL,        -- (S) adds up within one area+version+method+conditions, not across them
    _batch_id bigint, _loaded_at timestamptz DEFAULT now(),
    PRIMARY KEY (location_area_key, pokemon_key, version_key, slot_seq)
);
CREATE INDEX IF NOT EXISTS ix_fe_pokemon ON mart.fact_encounter (pokemon_key);

-- Grain: one row per pokemon x item x version. ~2,500 rows.
CREATE TABLE IF NOT EXISTS mart.fact_pokemon_held_item (
    pokemon_key         integer  NOT NULL REFERENCES mart.dim_pokemon,
    item_key            integer  NOT NULL REFERENCES mart.dim_item,
    version_key         smallint NOT NULL REFERENCES mart.dim_version,
    rarity_pct          smallint NOT NULL,          -- (S) adds up per pokemon+version only
    _batch_id bigint, _loaded_at timestamptz DEFAULT now(),
    PRIMARY KEY (pokemon_key, item_key, version_key)
);

-- Grain: one row per evolution condition = chain x to_species x detail_seq.
-- One species-to-species step can have several alternative conditions
-- (per version group, per form), hence detail_seq. Uses ROLE-PLAYING
-- dimensions: dim_species twice (from/to, plus trade partner), dim_item
-- twice (used item / held item).
CREATE TABLE IF NOT EXISTS mart.fact_evolution (
    evolution_chain_id      integer  NOT NULL,      -- degenerate dimension
    to_species_key          integer  NOT NULL REFERENCES mart.dim_species,
    detail_seq              smallint NOT NULL,      -- degenerate dimension
    from_species_key        integer  NOT NULL REFERENCES mart.dim_species,
    evolution_trigger_key   smallint NOT NULL REFERENCES mart.dim_evolution_trigger,
    version_group_key       smallint NOT NULL REFERENCES mart.dim_version_group,
    used_item_key           integer  NOT NULL REFERENCES mart.dim_item,
    held_item_key           integer  NOT NULL REFERENCES mart.dim_item,
    known_move_key          integer  NOT NULL REFERENCES mart.dim_move,
    known_move_type_key     smallint NOT NULL REFERENCES mart.dim_type,
    trade_species_key       integer  NOT NULL REFERENCES mart.dim_species,
    location_id             integer,                -- no dim_location yet; kept as natural key
    stage                   smallint NOT NULL,      -- 1 = first evolution, 2 = second
    min_level               smallint,               -- (N)
    min_happiness           smallint,               -- (N)
    min_beauty              smallint,               -- (N)
    min_affection           smallint,               -- (N)
    time_of_day             text,
    gender_id               smallint,
    needs_overworld_rain    boolean NOT NULL,
    turn_upside_down        boolean NOT NULL,
    _batch_id bigint, _loaded_at timestamptz DEFAULT now(),
    PRIMARY KEY (evolution_chain_id, to_species_key, detail_seq)
);

-- FACTLESS FACT / BRIDGE with EFFECTIVE DATING. Grain: one row per
-- pokemon x slot x type-era. A pokemon's typing can change between
-- generations (Clefairy: normal until gen V, fairy from gen VI), so each
-- row is valid from one generation to another, like an SCD2 row but
-- versioned by generation instead of by calendar date.
CREATE TABLE IF NOT EXISTS mart.fact_pokemon_type (
    pokemon_key             integer  NOT NULL REFERENCES mart.dim_pokemon,
    slot                    smallint NOT NULL,      -- 1 = primary, 2 = secondary
    valid_from_generation   smallint NOT NULL,
    valid_to_generation     smallint NOT NULL DEFAULT 99, -- 99 = still current
    type_key                smallint NOT NULL REFERENCES mart.dim_type,
    is_current              boolean  NOT NULL,
    _batch_id bigint, _loaded_at timestamptz DEFAULT now(),
    PRIMARY KEY (pokemon_key, slot, valid_from_generation)
);

-- FACTLESS FACT. Grain: one row per pokemon x ability slot (1..3).
CREATE TABLE IF NOT EXISTS mart.fact_pokemon_ability (
    pokemon_key         integer  NOT NULL REFERENCES mart.dim_pokemon,
    slot                smallint NOT NULL,
    ability_key         integer  NOT NULL REFERENCES mart.dim_ability,
    is_hidden           boolean  NOT NULL,
    _batch_id bigint, _loaded_at timestamptz DEFAULT now(),
    PRIMARY KEY (pokemon_key, slot)
);

-- DENSE MATRIX FACT. Grain: one row per attacking type x defending type
-- x generation, for every pair of battle types that exist in that
-- generation. The API only lists the non-neutral pairs; the loader fills
-- in the 1x rows ("densification") so that a missing row always means
-- "this matchup did not exist", never "neutral". ~2,900 rows.
CREATE TABLE IF NOT EXISTS mart.fact_type_effectiveness (
    attacking_type_key  smallint NOT NULL REFERENCES mart.dim_type,
    defending_type_key  smallint NOT NULL REFERENCES mart.dim_type,
    generation_key      smallint NOT NULL REFERENCES mart.dim_generation,
    damage_multiplier   numeric(2,1) NOT NULL,      -- (N) 0, 0.5, 1, 2: multiply, never sum
    _batch_id bigint, _loaded_at timestamptz DEFAULT now(),
    PRIMARY KEY (attacking_type_key, defending_type_key, generation_key)
);

-- ===================== DERIVED / CONVENIENCE =========================

-- AGGREGATE "one big table" for dashboards. Grain: one row per pokemon.
-- Built from the star, never from raw, so there is one source of truth.
CREATE OR REPLACE VIEW mart.pokemon_profile AS
SELECT p.pokemon_key, p.pokemon_code, p.species_name, p.generation_number,
       p.primary_type, p.secondary_type, p.is_legendary, p.is_mythical,
       MAX(f.base_stat) FILTER (WHERE s.stat_code = 'hp')              AS hp,
       MAX(f.base_stat) FILTER (WHERE s.stat_code = 'attack')          AS attack,
       MAX(f.base_stat) FILTER (WHERE s.stat_code = 'defense')         AS defense,
       MAX(f.base_stat) FILTER (WHERE s.stat_code = 'special-attack')  AS special_attack,
       MAX(f.base_stat) FILTER (WHERE s.stat_code = 'special-defense') AS special_defense,
       MAX(f.base_stat) FILTER (WHERE s.stat_code = 'speed')           AS speed,
       SUM(f.base_stat)                                                AS base_stat_total
FROM mart.dim_pokemon p
JOIN mart.fact_pokemon_stat f USING (pokemon_key)
JOIN mart.dim_stat s USING (stat_key)
GROUP BY p.pokemon_key, p.pokemon_code, p.species_name, p.generation_number,
         p.primary_type, p.secondary_type, p.is_legendary, p.is_mythical;
