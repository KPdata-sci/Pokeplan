-- AGGREGATE "one big table" for dashboards. Grain: one row per pokemon,
-- CURRENT stats only. Built from the star, never from raw.
CREATE OR REPLACE VIEW mart.pokemon_profile AS
SELECT p.pokemon_key, p.pokemon_code, p.species_name, p.species_generation,
       p.introduced_generation, p.form_category, p.species_class,
       p.primary_type, p.secondary_type,
       MAX(f.base_stat) FILTER (WHERE s.stat_code = 'hp')              AS hp,
       MAX(f.base_stat) FILTER (WHERE s.stat_code = 'attack')          AS attack,
       MAX(f.base_stat) FILTER (WHERE s.stat_code = 'defense')         AS defense,
       MAX(f.base_stat) FILTER (WHERE s.stat_code = 'special-attack')  AS special_attack,
       MAX(f.base_stat) FILTER (WHERE s.stat_code = 'special-defense') AS special_defense,
       MAX(f.base_stat) FILTER (WHERE s.stat_code = 'speed')           AS speed,
       SUM(f.base_stat)                                                AS base_stat_total
FROM mart.dim_pokemon p
JOIN mart.fact_pokemon_stat f USING (pokemon_key)
JOIN mart.dim_stat s USING (stat_key)
WHERE f.is_current
GROUP BY p.pokemon_key, p.pokemon_code, p.species_name, p.species_generation,
         p.introduced_generation, p.form_category, p.species_class,
         p.primary_type, p.secondary_type;

-- AS-OF HELPER. Grain: one row per move x version group: the move exactly
-- as it worked in that game. Saves every query from repeating the SCD2
-- range join.
CREATE OR REPLACE VIEW mart.move_in_version_group AS
SELECT vg.version_group_key, vg.version_group_code, vg.generation_number,
       m.move_key, m.move_id, m.move_code, m.type_code, m.effective_damage_class,
       m.power, m.accuracy, m.pp, m.effect_chance
FROM mart.dim_version_group vg
JOIN mart.dim_move m
  ON vg.sort_order BETWEEN m.valid_from_order AND m.valid_to_order
WHERE vg.version_group_key <> 0 AND m.move_key <> 0
  AND m.introduced_generation <= vg.generation_number;
