-- =====================================================================
-- Pokeplan :: Layer 3 — MART (a.k.a. gold / presentation)
-- ---------------------------------------------------------------------
-- Kimball star schema. Rules applied throughout:
--   * Every table states its GRAIN (what one row means) before anything
--     else. Facts never mix grains.
--   * Dimensions get an integer SURROGATE key (<name>_key) plus the API's
--     NATURAL key (<name>_id). Facts join on surrogate keys only.
--   * Hierarchies are flattened into the dimension (denormalised), e.g.
--     version -> version group -> generation lives in dim_version. That is
--     what makes it a star and not a snowflake.
--   * Key 0 is the "Unknown / Not applicable" member in every dimension,
--     so facts never hold NULL foreign keys and inner joins never drop rows.
--   * Every row carries audit columns (_batch_id, _loaded_at, _row_hash).
--   * Dimensions are SCD type 1 (overwrite) unless stated otherwise.
--
-- v2 (domain refactor). The Pokémon games are a 30-year timeline, and the
-- same thing (a move, a Pokémon's stats, the type chart) means different
-- things in different games. Two time axes are used:
--   * GENERATION (1..9) for Pokémon attributes: types, stats, abilities,
--     type chart. Columns valid_from_generation / valid_to_generation,
--     99 = still current. Rows never start before the mechanic existed
--     (no abilities before gen III) or before the Pokémon existed.
--   * VERSION GROUP sort_order for moves, because moves change between
--     games inside one generation too. dim_move is SCD type 2 on it.
-- =====================================================================

CREATE SCHEMA IF NOT EXISTS mart;

-- ============================ DIMENSIONS =============================

-- Grain: one row per generation (I .. IX). 9 rows.
CREATE TABLE IF NOT EXISTS mart.dim_generation (
    generation_key      smallint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    generation_id       smallint NOT NULL UNIQUE,
    generation_code     text     NOT NULL,          -- 'generation-i'
    generation_name     text,                       -- 'Generation I'
    generation_number   smallint NOT NULL,          -- 1 (sortable)
    roman               text,                       -- 'I'
    main_region_code    text,                       -- the NEW region of that generation
    first_release_year  smallint,                   -- from ref.generation_info
    last_release_year   smallint,
    platform            text,
    mechanics_introduced text,                      -- e.g. 'abilities, natures'
    _batch_id bigint, _loaded_at timestamptz DEFAULT now(), _row_hash text
);

-- Grain: one row per version group = one game release (often a pair of
-- versions: Red and Blue). 32 rows. A version group's generation is when
-- it was RELEASED, not where it is set: HeartGold/SoulSilver are a gen IV
-- remake of the gen II games, set in Johto and Kanto.
CREATE TABLE IF NOT EXISTS mart.dim_version_group (
    version_group_key   smallint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version_group_id    smallint NOT NULL UNIQUE,
    version_group_code  text     NOT NULL,          -- 'red-blue'
    sort_order          smallint,                   -- global release order: the move-history timeline
    generation_id       smallint,                   -- denormalised hierarchy
    generation_code     text,
    generation_number   smallint,
    release_year        smallint,                   -- from ref.version_group_info
    game_category       text,                       -- core / enhanced / remake / dlc / spin-off / japan-only
    base_version_group_code text,                   -- DLC -> its base game
    remake_of_generation smallint,
    region_codes        text,                       -- 'johto,kanto' (bridge_version_group_region has the rows)
    -- data coverage flags, set at the end of each load from the facts.
    -- PokeAPI has no encounter data after Sword/Shield, and DLC learnsets
    -- are folded into the base game.
    has_learnset_data   boolean,
    has_encounter_data  boolean,
    _batch_id bigint, _loaded_at timestamptz DEFAULT now(), _row_hash text
);

-- Grain: one row per individual game version. 53 rows.
CREATE TABLE IF NOT EXISTS mart.dim_version (
    version_key         smallint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version_id          smallint NOT NULL UNIQUE,
    version_code        text     NOT NULL,          -- 'red'
    version_name        text,
    version_group_id    smallint,                   -- denormalised hierarchy
    version_group_code  text,
    game_category       text,
    release_year        smallint,
    generation_id       smallint,
    generation_code     text,
    generation_number   smallint,
    _batch_id bigint, _loaded_at timestamptz DEFAULT now(), _row_hash text
);

-- BRIDGE. Grain: one row per version group x region it takes place in.
-- Needed because the relationship is many-to-many (HGSS = Johto + Kanto).
CREATE TABLE IF NOT EXISTS mart.bridge_version_group_region (
    version_group_key   smallint NOT NULL REFERENCES mart.dim_version_group,
    region_code         text     NOT NULL,
    _batch_id bigint, _loaded_at timestamptz DEFAULT now(),
    PRIMARY KEY (version_group_key, region_code)
);

-- Grain: one row per Pokédex (national, kanto, paldea, kitakami, ...). 35 rows.
CREATE TABLE IF NOT EXISTS mart.dim_pokedex (
    pokedex_key         smallint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pokedex_id          smallint NOT NULL UNIQUE,
    pokedex_code        text     NOT NULL,
    pokedex_name        text,
    region_code         text,                       -- NULL for the national dex
    is_national         boolean,
    is_main_series      boolean,
    _batch_id bigint, _loaded_at timestamptz DEFAULT now(), _row_hash text
);

-- BRIDGE. Grain: one row per version group x Pokédex it uses.
CREATE TABLE IF NOT EXISTS mart.bridge_version_group_pokedex (
    version_group_key   smallint NOT NULL REFERENCES mart.dim_version_group,
    pokedex_key         smallint NOT NULL REFERENCES mart.dim_pokedex,
    _batch_id bigint, _loaded_at timestamptz DEFAULT now(),
    PRIMARY KEY (version_group_key, pokedex_key)
);

-- Grain: one row per type. 21 rows: the 18 battle types plus stellar
-- (Tera only), unknown (???) and shadow (Colosseum/XD).
CREATE TABLE IF NOT EXISTS mart.dim_type (
    type_key            smallint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    type_id             integer  NOT NULL UNIQUE,
    type_code           text     NOT NULL,          -- 'fire'
    type_name           text,
    introduced_generation smallint,
    type_role           text     NOT NULL DEFAULT 'standard', -- standard / tera-only / non-battle
    pre_split_damage_class text,                    -- physical/special for ALL its moves in gens I-III
    _batch_id bigint, _loaded_at timestamptz DEFAULT now(), _row_hash text
);

-- Grain: one row per stat. 9 rows: hp, attack, defense, special-attack,
-- special-defense, speed, the battle-only accuracy and evasion, and the
-- generation-I-only special.
CREATE TABLE IF NOT EXISTS mart.dim_stat (
    stat_key            smallint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    stat_id             smallint NOT NULL UNIQUE,
    stat_code           text     NOT NULL,
    stat_name           text,
    is_battle_only      boolean,
    valid_from_generation smallint,                 -- special: 1..1; special-attack: 2..
    valid_to_generation   smallint,
    display_order       smallint,
    _batch_id bigint, _loaded_at timestamptz DEFAULT now(), _row_hash text
);

-- Grain: one row per ability. ~370 rows.
CREATE TABLE IF NOT EXISTS mart.dim_ability (
    ability_key         integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ability_id          integer  NOT NULL UNIQUE,
    ability_code        text     NOT NULL,
    ability_name        text,
    short_effect        text,
    is_main_series      boolean,
    introduced_generation smallint,
    _batch_id bigint, _loaded_at timestamptz DEFAULT now(), _row_hash text
);

-- SCD TYPE 2. Grain: one row per move per ERA (a range of version groups
-- in which the move behaved the same). ~1,490 rows for ~940 moves.
--   move_id is the DURABLE key (same for every era of one move),
--   move_key is the surrogate key of one era. Facts store the move_key of
--   the era that was live in the fact's game, so a Red/Blue learnset row
--   points at the Normal-type, 10%-flinch Bite, and a Scarlet/Violet row
--   at the Dark-type, 30%-flinch Bite.
-- effective_damage_class applies the physical/special split: before
-- generation IV a damaging move's class came from its TYPE (all Fire moves
-- special, all Normal moves physical); from gen IV each move has its own.
CREATE TABLE IF NOT EXISTS mart.dim_move (
    move_key            integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    move_id             integer  NOT NULL,          -- durable key
    valid_from_order    smallint NOT NULL,          -- version_group.sort_order range
    valid_to_order      smallint NOT NULL,          -- 9999 = still current
    is_current          boolean  NOT NULL,
    era_generation      smallint,                   -- generation the era starts in
    move_code           text     NOT NULL,
    move_name           text,
    type_code           text,                       -- type IN THIS ERA
    damage_class        text,                       -- the move's own class (gen IV+ rule)
    effective_damage_class text,                    -- the class that applied in this era
    power               smallint,                   -- NULL for status moves
    accuracy            smallint,
    pp                  smallint,
    priority            smallint,
    effect_chance       smallint,
    target              text,
    ailment             text,
    move_category       text,
    introduced_generation smallint,
    _batch_id bigint, _loaded_at timestamptz DEFAULT now(), _row_hash text,
    UNIQUE (move_id, valid_from_order)
);

-- Grain: one row per item. ~2,200 rows.
CREATE TABLE IF NOT EXISTS mart.dim_item (
    item_key            integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    item_id             integer  NOT NULL UNIQUE,
    item_code           text     NOT NULL,
    item_name           text,
    category            text,
    cost                integer,
    fling_power         smallint,
    fling_effect        text,
    is_holdable         boolean,
    machine_kind        text,                       -- 'tm' / 'hm' / 'tr', NULL for other items
    _batch_id bigint, _loaded_at timestamptz DEFAULT now(), _row_hash text
);

-- Grain: one row per location area; location and region flattened in.
-- ~1,540 rows.
CREATE TABLE IF NOT EXISTS mart.dim_location_area (
    location_area_key   integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    location_area_id    integer  NOT NULL UNIQUE,
    location_area_code  text     NOT NULL,
    location_area_name  text,
    location_id         integer,
    location_code       text,
    location_name       text,
    region_code         text,
    _batch_id bigint, _loaded_at timestamptz DEFAULT now(), _row_hash text
);

-- Grain: one row per species (the "Pokédex entry": Raticate). 1,025 rows.
-- Used where the game treats all forms alike: evolution chains, Pokédexes.
CREATE TABLE IF NOT EXISTS mart.dim_species (
    species_key         integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    species_id          integer  NOT NULL UNIQUE,
    species_code        text     NOT NULL,
    species_name        text,
    genus               text,                       -- 'Mouse Pokémon'
    generation_number   smallint,
    evolution_chain_id  integer,
    species_class       text,                       -- baby / legendary / mythical / regular
    is_baby             boolean,
    is_legendary        boolean,
    is_mythical         boolean,
    capture_rate        smallint,
    base_happiness      smallint,
    gender_rate         smallint,                   -- eighths female, -1 = genderless
    has_gender_differences boolean,
    hatch_counter       smallint,
    growth_rate         text,
    color               text,
    shape               text,
    habitat             text,
    variety_count       smallint,                   -- how many dim_pokemon rows it has
    _batch_id bigint, _loaded_at timestamptz DEFAULT now(), _row_hash text
);

-- Grain: one row per pokemon = one battle-relevant variety of a species.
-- 1,351 rows for 1,025 species. raticate and raticate-alola are two rows;
-- charizard-mega-x and charizard-gmax are rows too. Purely cosmetic forms
-- (Unown A..Z, Vivillon patterns) are NOT rows: they share stats, types
-- and moves, so they are counted in cosmetic_form_count instead.
-- form_category tells them apart, so "all Pokémon" questions can choose:
--   default    the species' standard variety (1,025 rows)
--   regional   Alolan / Galarian / Hisuian / Paldean variants
--   mega, primal, gigantamax, totem   temporary or battle-only transformations
--   battle-only  other in-battle forms (Aegislash Blade, Darmanitan Zen)
--   alternate  permanent alternative varieties (Rotom appliances, Therian forms)
CREATE TABLE IF NOT EXISTS mart.dim_pokemon (
    pokemon_key         integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pokemon_id          integer  NOT NULL UNIQUE,
    pokemon_code        text     NOT NULL,          -- 'raticate-alola'
    is_default_form     boolean,
    form_category       text,
    form_region_code    text,                       -- regional variants: 'alola', ...
    is_battle_only      boolean,
    is_mega             boolean,
    cosmetic_form_count smallint,                   -- extra cosmetic forms (Unown: 27)
    introduced_version_group text,                  -- when THIS variety first appeared
    introduced_generation smallint,                 -- raichu-alola: 7, though raichu is gen I
    height_m            numeric(5,1),               -- API gives decimetres
    weight_kg           numeric(6,1),               -- API gives hectograms
    base_experience     smallint,
    primary_type        text,                       -- current typing, convenience copy
    secondary_type      text,
    -- denormalised from species
    species_id          integer,
    species_code        text,
    species_name        text,
    species_generation  smallint,
    species_class       text,
    is_legendary        boolean,
    is_mythical         boolean,
    is_baby             boolean,
    capture_rate        smallint,
    growth_rate         text,
    color               text,
    habitat             text,
    _batch_id bigint, _loaded_at timestamptz DEFAULT now(), _row_hash text
);

-- Grain: one row per move learn method (level-up, machine, egg, tutor,
-- plus game-specific ones such as xd-shadow and Pokémon Champions' train).
CREATE TABLE IF NOT EXISTS mart.dim_learn_method (
    learn_method_key    smallint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    learn_method_id     smallint NOT NULL UNIQUE,
    learn_method_code   text     NOT NULL,
    learn_method_name   text,
    _batch_id bigint, _loaded_at timestamptz DEFAULT now(), _row_hash text
);

-- Grain: one row per encounter method (66: walk, surf, old-rod, gift,
-- overworld, max-raid, ...). method_group and chance_unit come from
-- ref.encounter_method_rule and say what fact_encounter.chance_pct means.
CREATE TABLE IF NOT EXISTS mart.dim_encounter_method (
    encounter_method_key  smallint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    encounter_method_id   smallint NOT NULL UNIQUE,
    encounter_method_code text     NOT NULL,
    encounter_method_name text,
    method_group          text,                     -- land / water / fishing / overworld / raid / roaming / one-off
    chance_unit           text,                     -- percent / weight / n/a
    _batch_id bigint, _loaded_at timestamptz DEFAULT now(), _row_hash text
);

-- JUNK DIMENSION. Grain: one row per distinct *combination* of encounter
-- condition values (e.g. 'season-winter,time-night'). An encounter can
-- have 0..n conditions from 30 condition types (time, season, weather,
-- swarm, radar, GBA cartridge in slot 2, story progress, ...). Instead of
-- a bridge table we store each observed combination once and give the
-- fact a single key. Key 0 = no condition.
CREATE TABLE IF NOT EXISTS mart.dim_encounter_condition_set (
    condition_set_key   integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    condition_set_code  text     NOT NULL UNIQUE,   -- sorted, comma-joined values; '' = none
    condition_types     text     NOT NULL,          -- sorted, comma-joined types: 'season,time'
    condition_count     smallint NOT NULL,
    has_time_condition    boolean NOT NULL,
    has_season_condition  boolean NOT NULL,
    has_weather_condition boolean NOT NULL,
    has_swarm_condition   boolean NOT NULL,
    has_story_condition   boolean NOT NULL,
    _batch_id bigint, _loaded_at timestamptz DEFAULT now()
);

-- Grain: one row per evolution trigger (18: level-up, trade, use-item,
-- shed, spin, three-critical-hits, agile-style-move, gimmighoul-coins...).
CREATE TABLE IF NOT EXISTS mart.dim_evolution_trigger (
    evolution_trigger_key  smallint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    evolution_trigger_id   smallint NOT NULL UNIQUE,
    evolution_trigger_code text     NOT NULL,
    evolution_trigger_name text,
    _batch_id bigint, _loaded_at timestamptz DEFAULT now(), _row_hash text
);

-- ============================== FACTS ================================
-- Fact types used:
--   transaction-style  : fact_pokemon_move, fact_encounter, fact_evolution
--   attribute snapshot : fact_pokemon_stat, fact_pokemon_held_item
--   factless           : fact_pokemon_type, fact_pokemon_ability,
--                        fact_pokedex_entry, fact_machine
--   dense matrix       : fact_type_effectiveness
-- Measures are tagged additive (A), semi-additive (S), non-additive (N).

-- Grain: one row per pokemon x move x version_group x learn_method x level.
-- The largest table (~640k rows). Level is part of the grain because a
-- Pokémon can learn the same move at several levels (Smeargle: Sketch at
-- 1, 11, 21 ... 91). Answers "which moves can X learn in game Y, how, and
-- at what level". COUNT(DISTINCT move_key) = movepool size.
-- move_key points at the dim_move ERA live in that version group.
CREATE TABLE IF NOT EXISTS mart.fact_pokemon_move (
    pokemon_key         integer  NOT NULL REFERENCES mart.dim_pokemon,
    move_key            integer  NOT NULL REFERENCES mart.dim_move,
    version_group_key   smallint NOT NULL REFERENCES mart.dim_version_group,
    learn_method_key    smallint NOT NULL REFERENCES mart.dim_learn_method,
    level_learned_at    smallint NOT NULL,          -- (N) 0 when not level-up
    learn_order         smallint,                   -- (N) tie-break within a level
    is_evolution_move   boolean  NOT NULL,          -- level-up at level 0 = learned on evolving (gen VII+)
    _batch_id bigint, _loaded_at timestamptz DEFAULT now(),
    PRIMARY KEY (pokemon_key, move_key, version_group_key, learn_method_key, level_learned_at)
);
CREATE INDEX IF NOT EXISTS ix_fpm_move ON mart.fact_pokemon_move (move_key);
CREATE INDEX IF NOT EXISTS ix_fpm_vg   ON mart.fact_pokemon_move (version_group_key);

-- EFFECTIVE-DATED. Grain: one row per pokemon x stat x stat-era.
-- Base stats changed between generations (Pikachu's defence and special
-- defence rose in gen VI) and gen I had one Special stat instead of two.
-- SUM(base_stat) over the six core stats of one era = Base Stat Total.
CREATE TABLE IF NOT EXISTS mart.fact_pokemon_stat (
    pokemon_key           integer  NOT NULL REFERENCES mart.dim_pokemon,
    stat_key              smallint NOT NULL REFERENCES mart.dim_stat,
    valid_from_generation smallint NOT NULL,
    valid_to_generation   smallint NOT NULL DEFAULT 99,  -- 99 = still current
    is_current            boolean  NOT NULL,
    base_stat             smallint NOT NULL,        -- (A across stats of one era, N across pokemon)
    effort_yield          smallint NOT NULL,        -- (A) EVs awarded when defeated
    _batch_id bigint, _loaded_at timestamptz DEFAULT now(),
    PRIMARY KEY (pokemon_key, stat_key, valid_from_generation)
);

-- Grain: one encounter slot = location_area x pokemon x version x slot_seq.
-- slot_seq is a DEGENERATE DIMENSION (the position in the source array):
-- the API can list two identical slots, and both are real.
-- Coverage: PokeAPI has encounter data up to Sword/Shield and its DLC only.
CREATE TABLE IF NOT EXISTS mart.fact_encounter (
    location_area_key     integer  NOT NULL REFERENCES mart.dim_location_area,
    pokemon_key           integer  NOT NULL REFERENCES mart.dim_pokemon,
    version_key           smallint NOT NULL REFERENCES mart.dim_version,
    slot_seq              smallint NOT NULL,        -- degenerate dimension
    encounter_method_key  smallint NOT NULL REFERENCES mart.dim_encounter_method,
    condition_set_key     integer  NOT NULL REFERENCES mart.dim_encounter_condition_set,
    min_level             smallint NOT NULL,        -- (N)
    max_level             smallint NOT NULL,        -- (N)
    chance_pct            smallint NOT NULL,        -- (S) adds up within one area+version+method+conditions,
                                                    --     and is a percentage only when
                                                    --     dim_encounter_method.chance_unit = 'percent'
    _batch_id bigint, _loaded_at timestamptz DEFAULT now(),
    PRIMARY KEY (location_area_key, pokemon_key, version_key, slot_seq)
);
CREATE INDEX IF NOT EXISTS ix_fe_pokemon ON mart.fact_encounter (pokemon_key);

-- Grain: one row per pokemon x item x version. ~5,400 rows.
CREATE TABLE IF NOT EXISTS mart.fact_pokemon_held_item (
    pokemon_key         integer  NOT NULL REFERENCES mart.dim_pokemon,
    item_key            integer  NOT NULL REFERENCES mart.dim_item,
    version_key         smallint NOT NULL REFERENCES mart.dim_version,
    rarity_pct          smallint NOT NULL,          -- (S) adds up per pokemon+version only
    _batch_id bigint, _loaded_at timestamptz DEFAULT now(),
    PRIMARY KEY (pokemon_key, item_key, version_key)
);

-- Grain: one row per evolution condition = chain x to_species x detail_seq.
-- One species-to-species step can have several alternative conditions
-- (per game, per region, per form), hence detail_seq. Uses ROLE-PLAYING
-- dimensions: dim_species (from / to / trade partner / party member),
-- dim_item (used / held), dim_move (known / used), dim_type (known move
-- type / party type). from_pokemon_key / to_pokemon_key resolve the step
-- to concrete varieties: Pikachu -> Raichu (Thunder Stone) and
-- Pikachu -> Alolan Raichu (Thunder Stone, in Alola) are separate rows.
CREATE TABLE IF NOT EXISTS mart.fact_evolution (
    evolution_chain_id      integer  NOT NULL,      -- degenerate dimension
    to_species_key          integer  NOT NULL REFERENCES mart.dim_species,
    detail_seq              smallint NOT NULL,      -- degenerate dimension
    from_species_key        integer  NOT NULL REFERENCES mart.dim_species,
    from_pokemon_key        integer  NOT NULL REFERENCES mart.dim_pokemon,
    to_pokemon_key          integer  NOT NULL REFERENCES mart.dim_pokemon,
    evolution_trigger_key   smallint NOT NULL REFERENCES mart.dim_evolution_trigger,
    version_group_key       smallint NOT NULL REFERENCES mart.dim_version_group, -- game the rule was introduced in
    used_item_key           integer  NOT NULL REFERENCES mart.dim_item,
    held_item_key           integer  NOT NULL REFERENCES mart.dim_item,
    known_move_key          integer  NOT NULL REFERENCES mart.dim_move,
    used_move_key           integer  NOT NULL REFERENCES mart.dim_move,
    known_move_type_key     smallint NOT NULL REFERENCES mart.dim_type,
    party_type_key          smallint NOT NULL REFERENCES mart.dim_type,
    trade_species_key       integer  NOT NULL REFERENCES mart.dim_species,
    party_species_key       integer  NOT NULL REFERENCES mart.dim_species,
    location_id             integer,                -- no dim_location yet; kept as natural key
    region_code             text,                   -- only in this region (regional evolutions)
    stage                   smallint NOT NULL,      -- 1 = first evolution, 2 = second
    is_default_path         boolean  NOT NULL,
    min_level               smallint,               -- (N)
    min_happiness           smallint,               -- (N)
    min_beauty              smallint,               -- (N)
    min_affection           smallint,               -- (N)
    min_move_count          smallint,               -- (N) e.g. use Barb Barrage 20 times
    min_steps               smallint,               -- (N) Let's Go! walking evolutions
    min_damage_taken        smallint,               -- (N)
    relative_physical_stats smallint,               -- Tyrogue: 1 atk>def, 0 equal, -1 atk<def
    time_of_day             text,
    gender_id               smallint,
    needs_overworld_rain    boolean NOT NULL,
    turn_upside_down        boolean NOT NULL,
    near_special_rock       boolean NOT NULL,
    needs_multiplayer       boolean NOT NULL,
    _batch_id bigint, _loaded_at timestamptz DEFAULT now(),
    PRIMARY KEY (evolution_chain_id, to_species_key, detail_seq)
);

-- FACTLESS FACT with EFFECTIVE DATING. Grain: one row per pokemon x slot
-- x type-era. A pokemon's typing can change between generations (Clefairy:
-- normal until gen V, fairy from gen VI), so each row is valid from one
-- generation to another, like an SCD2 row but versioned by generation.
CREATE TABLE IF NOT EXISTS mart.fact_pokemon_type (
    pokemon_key             integer  NOT NULL REFERENCES mart.dim_pokemon,
    slot                    smallint NOT NULL,      -- 1 = primary, 2 = secondary
    valid_from_generation   smallint NOT NULL,
    valid_to_generation     smallint NOT NULL DEFAULT 99, -- 99 = still current
    type_key                smallint NOT NULL REFERENCES mart.dim_type,
    is_current              boolean  NOT NULL,
    _batch_id bigint, _loaded_at timestamptz DEFAULT now(),
    PRIMARY KEY (pokemon_key, slot, valid_from_generation)
);

-- FACTLESS FACT with EFFECTIVE DATING. Grain: one row per pokemon x
-- ability slot x era. Abilities start in gen III and the hidden slot (3)
-- in gen V; some Pokémon swapped abilities later (Gengar: Levitate until
-- gen VI, Cursed Body from gen VII).
CREATE TABLE IF NOT EXISTS mart.fact_pokemon_ability (
    pokemon_key             integer  NOT NULL REFERENCES mart.dim_pokemon,
    slot                    smallint NOT NULL,      -- 1, 2 = regular; 3 = hidden
    valid_from_generation   smallint NOT NULL,
    valid_to_generation     smallint NOT NULL DEFAULT 99,
    ability_key             integer  NOT NULL REFERENCES mart.dim_ability,
    is_hidden               boolean  NOT NULL,
    is_current              boolean  NOT NULL,
    _batch_id bigint, _loaded_at timestamptz DEFAULT now(),
    PRIMARY KEY (pokemon_key, slot, valid_from_generation)
);

-- FACTLESS FACT. Grain: one row per species x Pokédex. ~8,000 rows.
-- How the games scope "which Pokémon are in this game": a game uses one or
-- more regional dexes (bridge_version_group_pokedex), each dex lists species.
CREATE TABLE IF NOT EXISTS mart.fact_pokedex_entry (
    species_key         integer  NOT NULL REFERENCES mart.dim_species,
    pokedex_key         smallint NOT NULL REFERENCES mart.dim_pokedex,
    entry_number        smallint NOT NULL,          -- (N) position in that dex
    _batch_id bigint, _loaded_at timestamptz DEFAULT now(),
    PRIMARY KEY (species_key, pokedex_key)
);

-- FACTLESS FACT. Grain: one row per machine item x version group.
-- ~2,370 rows. Which move a TM/HM/TR teaches depends on the game:
-- TM26 is Earthquake in 18 games, Scary Face in Sword/Shield.
CREATE TABLE IF NOT EXISTS mart.fact_machine (
    item_key            integer  NOT NULL REFERENCES mart.dim_item,
    version_group_key   smallint NOT NULL REFERENCES mart.dim_version_group,
    move_key            integer  NOT NULL REFERENCES mart.dim_move,
    machine_kind        text     NOT NULL,          -- tm / hm / tr
    machine_number      smallint,                   -- 26 for tm26
    _batch_id bigint, _loaded_at timestamptz DEFAULT now(),
    PRIMARY KEY (item_key, version_group_key)
);

-- DENSE MATRIX FACT. Grain: one row per attacking type x defending type
-- x generation, for every pair of STANDARD types that exist in that
-- generation (15 types in gen I, 17 in II-V, 18 from VI: 2,677 rows).
-- The API only lists the non-neutral pairs; the loader fills in the 1x
-- rows ("densification") so that a missing row always means "this matchup
-- did not exist", never "neutral". Legends: Arceus uses different numbers
-- (2.5x / 0.4x for doubled matchups) that the API does not carry.
CREATE TABLE IF NOT EXISTS mart.fact_type_effectiveness (
    attacking_type_key  smallint NOT NULL REFERENCES mart.dim_type,
    defending_type_key  smallint NOT NULL REFERENCES mart.dim_type,
    generation_key      smallint NOT NULL REFERENCES mart.dim_generation,
    damage_multiplier   numeric(2,1) NOT NULL,      -- (N) 0, 0.5, 1, 2: multiply, never sum
    _batch_id bigint, _loaded_at timestamptz DEFAULT now(),
    PRIMARY KEY (attacking_type_key, defending_type_key, generation_key)
);

